def setk(d, path, v):
    ks = path.split('.')
    for k in ks[:-1]:
        d = d.setdefault(k, {})
    d[ks[-1]] = v

def delk(d, path):
    ks = path.split('.')
    for k in ks[:-1]:
        d = d.get(k, {})
    d.pop(ks[-1], None)

